async function loadBlogPreview() {
  const box = document.getElementById("blogPreview");
  try {
    const res = await fetch("/api/posts");
    if (!res.ok) throw new Error();
    const posts = await res.json();
    box.innerHTML = posts.slice(0, 3).map(p => `
      <article class="card">
        <div class="card-body">
          <div class="card-top"><span class="days" style="margin:0">${fmtDate(p.createdAt)}</span></div>
          <h3 class="card-title blog-card-title">${p.title}</h3>
          <p class="card-desc" style="min-height:3.4em">${p.excerpt}</p>
          <a class="btn btn-outline btn-block" href="blog.html?post=${encodeURIComponent(p.id)}">${T(currentLang, "bp.read")}</a>
        </div>
      </article>`).join("");
  } catch (e) { /* silencieux */ }
}
function fmtDate(iso) {
  if (!iso) return "";
  return new Date(iso).toLocaleDateString(currentLang, { day: "numeric", month: "long" });
}

