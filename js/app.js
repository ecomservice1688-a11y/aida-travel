async function loadDepartures() {
  const box = document.getElementById("depList");
  try {
    const res = await fetch("/api/departures");
    if (!res.ok) throw new Error();
    const list = await res.json();
    if (!list.length) return;
    const lang = currentLang;
    const dateSel = document.getElementById("fDate");
    if (dateSel && !dateSel.dataset.filled) {
      dateSel.dataset.filled = "1";
      list.forEach(d => {
        const opt = document.createElement("option");
        opt.value = d.date;
        opt.textContent = new Date(d.date).toLocaleDateString(lang, { day: "numeric", month: "short", year: "numeric" }) + " — " + d.tourTitle;
        dateSel.appendChild(opt);
      });
    }
    box.innerHTML = list.slice(0, 6).map(d => `
      <a class="dep-card" href="#contact" data-tour="${d.tourId}" data-date="${d.date}">
        <div class="dep-date"><span class="dep-d">${new Date(d.date).toLocaleDateString(lang, { day: "numeric", month: "short" })}</span></div>
        <div class="dep-info">
          <b>${d.tourTitle}</b>
          <small>${d.tourLoc} · ${d.places} ${T(lang, "dp.places")}</small>
        </div>
        <div class="dep-price"><b>Sur demande</b></div>
        <span class="btn btn-primary btn-sm">${T(lang, "dp.book")}</span>
      </a>`).join("");
    box.querySelectorAll(".dep-card").forEach(a => a.addEventListener("click", preselectQuote));
  } catch (e) { /* silencieux */ }
}

function preselectQuote(e) {
  const el = e.currentTarget;
  if (el.dataset.tour) {
    const sel = document.getElementById("fCircuit");
    if (sel && el.dataset.tour) sel.value = el.dataset.tour;
    focusQuoteForm();
  }
  if (el.dataset.date) {
    const ds = document.getElementById("fDate");
    if (ds && el.dataset.date) ds.value = el.dataset.date;
  }
}
function focusQuoteForm() {
  const form = document.getElementById("contactForm");
  if (form) setTimeout(() => form.scrollIntoView({ behavior: "smooth", block: "center" }), 120);
}
document.addEventListener("click", e => {
  const a = e.target.closest(".quote-link[data-tour]");
  if (a) {
    const sel = document.getElementById("fCircuit");
    if (sel) sel.value = a.dataset.tour;
    focusQuoteForm();
  }
});

